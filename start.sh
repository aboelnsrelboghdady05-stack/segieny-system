#!/usr/bin/env bash
# ========================================================
# تشغيل منظومة شركة مقاولات السجيني
# ========================================================

DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
cd "$DIR"

echo "========================================================"
echo "    شركة مقاولات السجيني - المنظومة الرقمية لإدارة المشاريع"
echo "========================================================"

# التحقق من وجود بيئة العمل
if [ ! -d "venv" ]; then
    echo "جاري تجهيز بيئة التشغيل لأول مرة..."
    python3 -m venv venv
    ./venv/bin/pip install -r requirements.txt
fi

echo "تشغيل الخادم على الرابط: http://localhost:5001"
echo "يتم الآن فتح المتصفح تلقائياً..."

# فتح المتصفح بعد ثانية
(sleep 1.5 && open "http://localhost:5001") &

# تشغيل التطبيق
./venv/bin/python3 app.py
